-- Public may inspect active coupons through the secure validation RPC only; do not expose raw coupon rows.
-- Public may create orders only through public.place_order_secure().
CREATE OR REPLACE FUNCTION public.place_order_secure(
  p_customer JSONB,
  p_items JSONB,
  p_coupon_code TEXT DEFAULT NULL,
  p_payment_method TEXT DEFAULT 'COD'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_customer_id UUID;
  v_order_id BIGINT;
  v_order_number TEXT;
  v_subtotal NUMERIC(12,2) := 0;
  v_discount NUMERIC(12,2) := 0;
  v_offer_discount NUMERIC(12,2) := 0;
  v_shipping NUMERIC(12,2) := 0;
  v_tax NUMERIC(12,2) := 0;
  v_total NUMERIC(12,2) := 0;
  v_coupon coupons%ROWTYPE;
  v_offer offers%ROWTYPE;
  v_coupon_discount NUMERIC(12,2) := 0;
  v_eligible_subtotal NUMERIC(12,2) := 0;
  v_item JSONB;
  v_product products%ROWTYPE;
  v_qty INTEGER;
  v_line NUMERIC(12,2);
  v_now TIMESTAMPTZ := NOW();
BEGIN
  IF p_items IS NULL OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Cart is empty';
  END IF;

  INSERT INTO public.customers(user_id, full_name, email, phone)
  VALUES (auth.uid(), COALESCE(p_customer->>'full_name','Guest Customer'), lower(trim(COALESCE(p_customer->>'email',''))), NULLIF(p_customer->>'phone',''))
  ON CONFLICT DO NOTHING;

  SELECT id INTO v_customer_id
  FROM public.customers
  WHERE lower(email)=lower(trim(COALESCE(p_customer->>'email','')))
  ORDER BY created_at ASC LIMIT 1;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    v_qty := GREATEST(1, LEAST(100, COALESCE((v_item->>'quantity')::INTEGER, 1)));
    SELECT * INTO v_product FROM public.products WHERE id = (v_item->>'product_id')::BIGINT AND status='Active' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Product % is unavailable', v_item->>'product_id'; END IF;
    IF COALESCE(v_product.stock_quantity,0) < v_qty THEN RAISE EXCEPTION 'Insufficient stock for %', v_product.name; END IF;
    v_line := COALESCE(v_product.price, v_product.regular_price, 0) * v_qty;
    v_subtotal := v_subtotal + v_line;
  END LOOP;

  -- Highest-priority active automatic offer. One automatic offer is applied to prevent accidental stacking.
  SELECT * INTO v_offer
  FROM public.offers
  WHERE active=true
    AND (starts_at IS NULL OR starts_at <= v_now)
    AND (expires_at IS NULL OR expires_at >= v_now)
    AND v_subtotal >= minimum_order_value
  ORDER BY priority ASC, discount_value DESC
  LIMIT 1;

  IF v_offer.id IS NOT NULL THEN
    IF v_offer.offer_type='percentage' THEN v_offer_discount := ROUND(v_subtotal * v_offer.discount_value/100,2);
    ELSIF v_offer.offer_type='fixed' THEN v_offer_discount := LEAST(v_subtotal, v_offer.discount_value);
    END IF;
  END IF;

  IF p_coupon_code IS NOT NULL AND trim(p_coupon_code) <> '' THEN
    SELECT * INTO v_coupon FROM public.coupons WHERE upper(code)=upper(trim(p_coupon_code)) AND active=true LIMIT 1;
    IF NOT FOUND THEN RAISE EXCEPTION 'Invalid or inactive coupon code'; END IF;
    IF v_coupon.starts_at IS NOT NULL AND v_coupon.starts_at > v_now THEN RAISE EXCEPTION 'Coupon is not active yet'; END IF;
    IF v_coupon.expires_at IS NOT NULL AND v_coupon.expires_at < v_now THEN RAISE EXCEPTION 'Coupon has expired'; END IF;
    IF v_subtotal < v_coupon.minimum_order_value THEN RAISE EXCEPTION 'Minimum order value for coupon is ₹%', v_coupon.minimum_order_value;
    END IF;
    IF v_coupon.usage_limit IS NOT NULL AND (SELECT COUNT(*) FROM public.coupon_usages WHERE coupon_id=v_coupon.id) >= v_coupon.usage_limit THEN
      RAISE EXCEPTION 'Coupon usage limit reached';
    END IF;
    IF v_coupon.discount_type='percentage' THEN v_coupon_discount := ROUND((v_subtotal - LEAST(v_offer_discount,v_subtotal)) * v_coupon.discount_value/100,2);
    ELSIF v_coupon.discount_type='fixed' THEN v_coupon_discount := LEAST(v_subtotal - LEAST(v_offer_discount,v_subtotal), v_coupon.discount_value);
    ELSIF v_coupon.discount_type='free_shipping' THEN v_coupon_discount := 0; v_shipping := 0;
    END IF;
    IF v_coupon.maximum_discount IS NOT NULL THEN v_coupon_discount := LEAST(v_coupon_discount, v_coupon.maximum_discount); END IF;
  END IF;

  v_discount := LEAST(v_subtotal, v_offer_discount + v_coupon_discount);
  v_total := GREATEST(0, v_subtotal - v_discount + v_shipping + v_tax);

  v_order_number := 'RJ-' || TO_CHAR(v_now,'YYYYMMDD') || '-' || LPAD(nextval('public.royra_order_number_seq')::TEXT,6,'0');

  INSERT INTO public.orders(
    order_number, customer_id, customer_name, customer_email, customer_phone,
    shipping_address, billing_address, subtotal, discount_total, coupon_code,
    offer_discount, shipping_amount, tax_amount, total_amount, currency,
    payment_method, payment_status, order_status
  ) VALUES (
    v_order_number, v_customer_id,
    COALESCE(p_customer->>'full_name','Guest Customer'),
    lower(trim(COALESCE(p_customer->>'email',''))), NULLIF(p_customer->>'phone',''),
    COALESCE(p_customer->'shipping_address','{}'::jsonb),
    COALESCE(p_customer->'billing_address',COALESCE(p_customer->'shipping_address','{}'::jsonb)),
    v_subtotal, v_discount, NULLIF(upper(trim(p_coupon_code)) ,''),
    v_offer_discount, v_shipping, v_tax, v_total, 'INR',
    COALESCE(p_payment_method,'COD'), 'Pending', 'Pending Payment'
  ) RETURNING id INTO v_order_id;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    v_qty := GREATEST(1, LEAST(100, COALESCE((v_item->>'quantity')::INTEGER, 1)));
    SELECT * INTO v_product FROM public.products WHERE id = (v_item->>'product_id')::BIGINT FOR UPDATE;
    v_line := COALESCE(v_product.price, v_product.regular_price, 0) * v_qty;
    INSERT INTO public.order_items(order_id,product_id,product_name,sku,selected_size,selected_metal,unit_price,quantity,line_total)
    VALUES(v_order_id,v_product.id,v_product.name,v_product.sku,v_item->>'size',v_item->>'metal',COALESCE(v_product.price,v_product.regular_price,0),v_qty,v_line);
    UPDATE public.products SET stock_quantity=GREATEST(0,stock_quantity-v_qty), updated_at=NOW() WHERE id=v_product.id;
    INSERT INTO public.inventory_movements(product_id,quantity_change,movement_type,reason,reference_type,reference_id)
    VALUES(v_product.id,-v_qty,'SALE','Customer order','order',v_order_number);
  END LOOP;

  INSERT INTO public.order_status_history(order_id,status,note,changed_by) VALUES(v_order_id,'Pending Payment','Order created',auth.uid());
  INSERT INTO public.payments(order_id,payment_method,amount,status) VALUES(v_order_id,COALESCE(p_payment_method,'COD'),v_total,'Pending');
  INSERT INTO public.shipments(order_id,status) VALUES(v_order_id,'Pending');

  IF v_coupon.id IS NOT NULL THEN
    INSERT INTO public.coupon_usages(coupon_id,order_id,customer_id,discount_amount) VALUES(v_coupon.id,v_order_id,v_customer_id,v_coupon_discount);
  END IF;

  RETURN jsonb_build_object('success',true,'order_id',v_order_id,'order_number',v_order_number,'subtotal',v_subtotal,'discount',v_discount,'total',v_total,'payment_status','Pending');
END;
$$;

