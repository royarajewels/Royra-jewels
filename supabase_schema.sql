CREATE OR REPLACE FUNCTION public.validate_coupon_secure(p_code TEXT, p_subtotal NUMERIC)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE c coupons%ROWTYPE; v_discount NUMERIC(12,2) := 0; v_now TIMESTAMPTZ := NOW();
BEGIN
  SELECT * INTO c FROM public.coupons WHERE UPPER(code)=UPPER(TRIM(p_code)) AND active=true LIMIT 1;
  IF NOT FOUND THEN RETURN jsonb_build_object('valid',false,'error','Invalid or inactive coupon'); END IF;
  IF c.starts_at IS NOT NULL AND c.starts_at>v_now THEN RETURN jsonb_build_object('valid',false,'error','Coupon is not active yet'); END IF;
  IF c.expires_at IS NOT NULL AND c.expires_at<v_now THEN RETURN jsonb_build_object('valid',false,'error','Coupon has expired'); END IF;
  IF p_subtotal < c.minimum_order_value THEN RETURN jsonb_build_object('valid',false,'error',format('Minimum order value is ₹%s',c.minimum_order_value)); END IF;
  IF c.usage_limit IS NOT NULL AND (SELECT COUNT(*) FROM public.coupon_usages WHERE coupon_id=c.id)>=c.usage_limit THEN RETURN jsonb_build_object('valid',false,'error','Coupon usage limit reached'); END IF;
  IF c.discount_type='percentage' THEN v_discount:=ROUND(p_subtotal*c.discount_value/100,2); ELSIF c.discount_type='fixed' THEN v_discount:=LEAST(p_subtotal,c.discount_value); ELSE v_discount:=0; END IF;
  IF c.maximum_discount IS NOT NULL THEN v_discount:=LEAST(v_discount,c.maximum_discount); END IF;
  RETURN jsonb_build_object('valid',true,'discount',v_discount,'code',c.code,'discount_type',c.discount_type);
END; $$;
GRANT EXECUTE ON FUNCTION public.validate_coupon_secure(TEXT,NUMERIC) TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.update_order_status_secure(p_order_id BIGINT, p_status TEXT, p_note TEXT DEFAULT NULL)
RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Admin access required'; END IF;
  UPDATE public.orders SET order_status=p_status, updated_at=NOW() WHERE id=p_order_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Order not found'; END IF;
  INSERT INTO public.order_status_history(order_id,status,note,changed_by) VALUES(p_order_id,p_status,p_note,auth.uid());
  RETURN jsonb_build_object('success',true);
END; $$;
GRANT EXECUTE ON FUNCTION public.update_order_status_secure(BIGINT,TEXT,TEXT) TO authenticated;
